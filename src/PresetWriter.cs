// PresetWriter — generates the files that make up one MSYS2 agent preset, and
// installs or removes them.
//
// The generated composition is the successor to the old two-plane MSYS2 setup
// (a host-plane profiles/web/cordis.patch.yml plus a launch-msys-profile.cmd
// that pre-pended MSYS2's usr\bin to PATH). None of that is needed any more:
// the preset carries its own shell argv, so the host launch environment is
// irrelevant and the user just runs `npx @deepseek-ai/dsh web` and picks a
// flavour from the roster.

using System;
