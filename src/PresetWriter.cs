        /// <summary>
        /// A README beside the preset. The preset is otherwise a black box of
        /// YAML; this records the exact invocation so a failure can be
        /// reproduced by hand without reading the shim's source.
        /// </summary>
        public static string RenderReadme(Msys2Flavour flavour, string shellCmd, string shimExe)
        {
            var sb = new StringBuilder();
            sb.Append("# ").Append(flavour.Label).Append(" — DSH agent preset\n\n");
            sb.Append("Installed by the DSH MSYS2 installer. Reinstalling overwrites these files.\n\n");
            sb.Append("## What runs\n\n");
            sb.Append("Every agent command goes through `").Append(ShimExeName).Append("`, which invokes:\n\n");
            sb.Append("    \"`").Append(shellCmd).Append("`\" ")
              .Append("-defterm -no-start -use-full-path ").Append(flavour.ShellFlag)
              .Append(" -here -c \"<your command>\"\n\n");
            sb.Append("The shim exists because DSH's pwsh executor spawns a fixed argv\n");
            sb.Append("(`-NoLogo -NoProfile -NonInteractive -Command <cmd>`) with `pwshPath` as\n");
            sb.Append("argv[0] of a direct spawn — and a `.cmd` cannot be argv[0] (Node returns\n");
            sb.Append("EINVAL for it). The shim is a real executable that strips the PowerShell\n");
            sb.Append("encoding preamble, writes the command to a temporary script, and runs the\n");
            sb.Append("invocation above with that script as its command.\n\n");
            sb.Append("## Environment\n\n");
            sb.Append("The shim reads its configuration from the environment:\n\n");
            sb.Append("| Variable | Value |\n| --- | --- |\n");
            sb.Append("| `DSH_MSYS2_SHELL_CMD` | `").Append(shellCmd).Append("` |\n");
            sb.Append("| `DSH_MSYS2_MSYSTEM` | `").Append(flavour.Msystem).Append("` |\n\n");
            sb.Append("## Reproducing a failure by hand\n\n");
            sb.Append("From a Windows prompt (this needs an unconfined shell — see below):\n\n");
            sb.Append("    \"").Append(shimExe).Append("\" -Command \"uname -s; echo $MSYSTEM\"\n\n");
            sb.Append("## Why this preset is unconfined\n\n");
            sb.Append("MSYS2 cannot start under the Windows ACL sandbox. `usr\\bin` loads\n");
            sb.Append("`msys-2.0.dll`, whose startup creates the per-user named section\n");
            sb.Append("`CreateFileMapping S-1-5-21-<user>-1001.1`; a write-restricted token denies it\n");
            sb.Append("with Win32 error 5, so `bash.exe` dies before running anything:\n\n");
            sb.Append("    bash.exe: *** fatal error - CreateFileMapping S-1-5-21-...-1001.1, Win32 error 5.\n\n");
            sb.Append("The preset therefore pins `danger-full-access`.\n\n");
            sb.Append("- MSYS2 install root: `").Append(Path.GetDirectoryName(Path.GetFullPath(shellCmd))).Append("`\n");
            sb.Append("- Shim: `").Append(shimExe).Append("`\n");
            return sb.ToString();
        }

        /// <summary>
        /// Write one file with LF endings and no BOM. A BOM in a YAML file is a
        /// needless variable, and these files are read by YAML tooling.
        /// </summary>
        private static void WriteTextFile(string path, string content)
        {
            File.WriteAllText(path, content, new UTF8Encoding(false));
        }

        /// <summary>
        /// Install one flavour's preset directory.
        ///
        /// Each file is written to a temporary name and then moved into place,
        /// so an interrupted run cannot leave a half-written composition that
        /// DSH's discovery would report as a broken roster row.
        ///
        /// `shimExe` may be null, in which case the shim is compiled into the
        /// preset directory directly.
        /// </summary>
        public static InstallResult Install(
            Msys2Flavour flavour,
            string shellCmd,
            string presetRoot,
            string shimExe)
        {
            string presetDir = Path.Combine(presetRoot, flavour.PresetId);
            Directory.CreateDirectory(presetDir);

            var result = new InstallResult();
            result.Flavour = flavour;
            result.PresetDir = presetDir;

            string presetShim = Path.Combine(presetDir, ShimExeName);
            if (shimExe == null)
            {
                ShimBuilder.Build(ShimBuilder.SourcePath(), presetShim);
            }
            else if (!string.Equals(
                Path.GetFullPath(shimExe), Path.GetFullPath(presetShim), StringComparison.OrdinalIgnoreCase))
            {
                File.Copy(shimExe, presetShim, true);
            }
            result.Written.Add(presetShim);

            var files = new Dictionary<string, string>();
            files[CompositionFileName] = RenderComposition(flavour, shellCmd, presetShim);
            files[MetadataFileName] = RenderMetadata(flavour);
            files[ReadmeFileName] = RenderReadme(flavour, shellCmd, presetShim);

            foreach (KeyValuePair<string, string> entry in files)
            {
                string target = Path.Combine(presetDir, entry.Key);
                string temp = target + ".tmp";
                WriteTextFile(temp, entry.Value);
                if (File.Exists(target)) File.Delete(target);
                File.Move(temp, target);
                result.Written.Add(target);
            }

            return result;
        }

        /// <summary>
        /// Install several flavours, compiling the shim only once.
        ///
        /// `progress` is called as (flavour, index, total) before each flavour,
        /// so the GUI can narrate without this class knowing about WinForms.
        /// </summary>
        public static List<InstallResult> InstallAll(
            IList<Msys2Flavour> flavours,
            string shellCmd,
            string presetRoot,
            Action<Msys2Flavour, int, int> progress)
        {
            // Compile once into a scratch directory OUTSIDE the preset root.
            // DSH's discovery scans every directory under the preset root and
            // reports one without a composition as a broken roster row, so a
            // helper directory left there would show up as a mystery preset.
            string scratch = Path.Combine(
                Path.GetTempPath(), "dsh-msys2-shim-build-" + Guid.NewGuid().ToString("N"));
            string shim;
            try
            {
                shim = ShimBuilder.Build(ShimBuilder.SourcePath(), Path.Combine(scratch, ShimExeName));

                var results = new List<InstallResult>();
                for (int i = 0; i < flavours.Count; i++)
                {
                    if (progress != null) progress(flavours[i], i + 1, flavours.Count);
                    results.Add(Install(flavours[i], shellCmd, presetRoot, shim));
                }
                return results;
            }
            finally
            {
                // The per-preset copies are what matter; the scratch copy is
                // only a build cache for this one run, and it lives outside the
                // preset root so cleanup is purely hygiene.
                try { if (Directory.Exists(scratch)) Directory.Delete(scratch, true); }
                catch (Exception) { }
            }
        }

        /// <summary>Remove one preset directory. False when nothing was there.</summary>
        public static bool Uninstall(Msys2Flavour flavour, string presetRoot)
        {
            string presetDir = Path.Combine(presetRoot, flavour.PresetId);
            if (!Directory.Exists(presetDir)) return false;
            Directory.Delete(presetDir, true);
            return true;
        }

        /// <summary>Which of our presets are currently on disk.</summary>
        public static List<Msys2Flavour> Installed(string presetRoot)
        {
            var found = new List<Msys2Flavour>();
            foreach (Msys2Flavour flavour in Msys2Flavours.All)
            {
                string composition = Path.Combine(presetRoot, flavour.PresetId, CompositionFileName);
                if (File.Exists(composition)) found.Add(flavour);
            }
            return found;
        }
