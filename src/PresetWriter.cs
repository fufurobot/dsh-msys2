        /// <summary>Single-quote a YAML scalar, doubling any embedded quote.</summary>
        public static string YamlQuote(string text)
        {
            return "'" + text.Replace("'", "''") + "'";
        }

        /// <summary>
        /// Forward slashes for a path that goes into YAML consumed on Windows.
        /// Node, cmd.exe and bash all accept them, and they avoid the escaping
        /// questions a backslash raises in any YAML scalar.
        /// </summary>
        public static string Posix(string windowsPath)
        {
            return windowsPath.Replace('\\', '/');
        }

        /// <summary>The picker metadata written beside a preset's composition.</summary>
        public static string RenderMetadata(Msys2Flavour flavour)
        {
            var sb = new StringBuilder();
            sb.Append("name: ").Append(YamlQuote("MSYS2 · " + flavour.Key)).Append('\n');
            sb.Append("description: ")
              .Append(YamlQuote(flavour.Label + " — " + flavour.Blurb))
              .Append('\n');
            return sb.ToString();
        }

